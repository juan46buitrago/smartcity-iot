import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = 'https://smartcitybga.duckdns.org';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
await ctx.addInitScript(() => { try { localStorage.setItem('scbga.bienvenida', '1'); } catch {} });
const page = await ctx.newPage();
const consoleErr = [];
page.on('console', (m) => m.type() === 'error' && consoleErr.push(m.text().slice(0, 140)));
let heartbeat = 0;
page.on('websocket', (ws) => ws.on('framereceived', (f) => { if (String(f.payload).includes('"heartbeat"')) heartbeat++; }));
await page.goto(BASE + '/', { waitUntil: 'domcontentloaded', timeout: 60000 });
await sleep(26000);
const tags = await page.evaluate(() => [...document.querySelectorAll('span')].filter((s) => /^(SIM|REAL)$/.test(s.textContent.trim())).length);
const footer = await page.getByText('Proyecto académico de la UNAB').count();
await page.goto(BASE + '/terminos', { waitUntil: 'domcontentloaded' });
await sleep(4000);
const terms = await page.getByText('Términos de uso').count();
const contact = await page.getByRole('heading', { name: 'Contacto' }).count();
const g = await (await fetch(BASE + '/grafana/login')).text();
console.log(JSON.stringify({ latidos_ws_en_26s: heartbeat, etiquetas_sim_real: tags, pie: footer, terminos: terms, contacto: contact, errores_csp: consoleErr.filter((e) => /font|Content Security/i.test(e)).length, errores_consola: consoleErr.length, grafana_version_visible: /"version":"\d+\.\d+/.test(g) || /v11\.\d+\.\d+/.test(g) }));
await b.close();
